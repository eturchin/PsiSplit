using System.Text;
using PsiSplit.Core.Models;

namespace PsiSplit.Core.Services;

/// <summary>
/// Generates a standard PAC file. Only the listed hosts are sent to the
/// filtered proxy; everything else stays DIRECT.
/// </summary>
public static class PacGenerator
{
    public static string Generate(IEnumerable<SiteRule> rules, int proxyPort)
    {
        var patterns = rules
            .Where(rule => rule.Enabled && !string.IsNullOrWhiteSpace(rule.Pattern))
            .Select(rule => rule.Pattern)
            .Distinct(StringComparer.OrdinalIgnoreCase)
            .ToArray();

        var sb = new StringBuilder();
        sb.AppendLine("// Generated by PsiSplit. Do not edit by hand.");
        sb.AppendLine($"// {DateTime.Now:yyyy-MM-dd HH:mm:ss}");
        sb.AppendLine("function FindProxyForURL(url, host) {");
        sb.AppendLine("  host = host.toLowerCase();");
        sb.AppendLine("  if (host.charAt(host.length - 1) === '.') host = host.substring(0, host.length - 1);");

        if (patterns.Length == 0)
        {
            sb.AppendLine("  return \"DIRECT\";");
        }
        else
        {
            foreach (var pattern in patterns)
            {
                sb.AppendLine($"  if ({BuildCondition(pattern)}) return \"PROXY 127.0.0.1:{proxyPort}; DIRECT\";");
            }

            sb.AppendLine("  return \"DIRECT\";");
        }

        sb.AppendLine("}");
        return sb.ToString();
    }

    private static string BuildCondition(string pattern)
    {
        if (pattern == "*")
        {
            return "true";
        }

        if (pattern.StartsWith("*.", StringComparison.Ordinal))
        {
            return $"dnsDomainIs(host, {Quote(pattern[1..])})";
        }

        if (pattern.Contains('*', StringComparison.Ordinal))
        {
            return $"shExpMatch(host, {Quote(pattern)})";
        }

        return $"(host === {Quote(pattern)} || dnsDomainIs(host, {Quote("." + pattern)}))";
    }

    private static string Quote(string value)
        => "\"" + value.Replace("\\", "\\\\", StringComparison.Ordinal)
                      .Replace("\"", "\\\"", StringComparison.Ordinal) + "\"";
}
